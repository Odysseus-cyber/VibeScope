select
    id as app_id,
    name,
    full_name,
    url,
    homepage,
    language,
    created_at,
    first_seen_at,
    last_observed_at,
    coalesce(nullif(category, ''), '未知') as category,
    coalesce(nullif(kind, ''), 'unknown') as kind,
    coalesce(nullif(evidence_level, ''), 'unknown') as evidence_level,
    case when jsonb_typeof(tools::jsonb) = 'array' then tools::jsonb else '[]'::jsonb end as tools,
    method,
    model,
    prompt_version,
    evidence::jsonb as evidence,
    classified_at,
    manual_override,
    stars,
    forks,
    (kind = 'application' and evidence_level = 'explicit') as is_eligible
from {{ source('operational', 'applications') }}
